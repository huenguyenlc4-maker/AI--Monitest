/**
 * Hàm lấy hoặc tự động cập nhật kho học liệu theo thời gian thực
 */
export function getCurriculumOutlines(
  filterGrade: string,
  filterSubject: string,
  filterCategory: RevisionCategory | 'all'
): DocumentOutline[] {
  return CURRICULUM_DATA.filter((doc) => {
    const matchGrade = filterGrade === 'all' || doc.grade === filterGrade;
    const matchSubject = filterSubject === 'all' || doc.subject === filterSubject;
    const matchCategory = filterCategory === 'all' || doc.category === filterCategory;
    return matchGrade && matchSubject && matchCategory;
  });
}
